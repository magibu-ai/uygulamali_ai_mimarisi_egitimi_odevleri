@spaces.GPU 
def predict(message, history):
    system_prompt = (
        "Sen yardımcı bir Finans Asistanısın. Sadece Türkçe yanıt ver.\n"
        "Kurallar:\n"
        "1. Kullanıcı paranın başka para birimindeki karşılığını sorduğunda 'convert_currency' kullan.\n"
        "2. Kripto para fiyatı için 'get_crypto_price' kullan.\n"
        "3. Alınacak kripto miktarını hesaplamak için 'calculate_crypto_purchase' kullan.\n"
        "4. Asla kafandan rakam sallama veya Türkçe dışı diller kullanma."
    )

    messages = [{"role": "system", "content": system_prompt}]

    if history:
        for item in history:
            if isinstance(item, (list, tuple)):
                if item[0]:
                    messages.append({"role": "user", "content": str(item[0])})
                if item[1]:
                    messages.append(
                        {"role": "assistant", "content": str(item[1])}
                    )
            elif isinstance(item, dict):
                messages.append(
                    {"role": item.get("role"), "content": item.get("content")}
                )

    messages.append({"role": "user", "content": message})

    trace_logs = []
    turn_counter = 1

    while turn_counter <= 5:
        try:
            response = client.chat.completions.create(
                model=MODEL_ID,
                messages=messages,
                tools=tools,
                tool_choice="auto",
                max_tokens=1000,
            )
        except Exception as e:
            return f"Model Bağlantı Hatası: {str(e)}"

        response_message = response.choices[0].message

        if response_message.tool_calls:
            messages.append(response_message)
            trace_logs.append(f"###  [Turn {turn_counter}] Araç Çağrıları:")

            for tool_call in response_message.tool_calls:
                func_name = tool_call.function.name
                func_args = json.loads(tool_call.function.arguments)

                trace_logs.append(f"  -> **{func_name}**({func_args})")

                if func_name in AVAILABLE_FUNCTIONS:
                    function_response = AVAILABLE_FUNCTIONS[func_name](
                        **func_args
                    )
                else:
                    function_response = {
                        "error": f"Tanımsız fonksiyon: {func_name}"
                    }

                trace_logs.append(f"  <- `{function_response}`")

                messages.append(
                    {
                        "tool_call_id": tool_call.id,
                        "role": "tool",
                        "name": func_name,
                        "content": json.dumps(function_response),
                    }
                )

            trace_logs.append("")
            turn_counter += 1
        else:
            final_reply = response_message.content
            formatted_logs = "\n".join(trace_logs)

            full_response = ""
            if formatted_logs:
                full_response += (
                    f"###  Arka Plan İşlem Adımları (Trace Log)\n\n"
                    f"{formatted_logs}\n---\n"
                )

            full_response += f"###  Yanıt:\n{final_reply}"
            return full_response

    return "Maksimum adım sayısına ulaşıldı."


