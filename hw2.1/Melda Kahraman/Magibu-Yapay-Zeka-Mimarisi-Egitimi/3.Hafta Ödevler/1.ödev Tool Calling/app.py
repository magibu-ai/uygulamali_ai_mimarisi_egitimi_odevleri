def get_crypto_price(coin_id: str, vs_currency: str = "usd") -> dict:
    coin_id = str(coin_id).lower().strip()
    vs_currency = str(vs_currency).lower().strip()
    url = f"https://api.coingecko.com/api/v3/simple/price?ids={coin_id}&vs_currencies={vs_currency}"
    headers = {"User-Agent": "Mozilla/5.0"}
    try:
        res = requests.get(url, headers=headers, timeout=5).json()
        if coin_id in res and vs_currency in res[coin_id]:
            return {
                "coin_id": coin_id,
                "vs_currency": vs_currency,
                "price": float(res[coin_id][vs_currency]),
            }
        return {
            "error": f"'{coin_id}' coini veya '{vs_currency}' para birimi bulunamadı."
        }
    except Exception as e:
        return {"error": f"API Hatası: {str(e)}"}


def convert_currency(amount, from_code: str, to_code: str = "USD") -> dict:
    try:
        amount = float(amount)
    except Exception:
        return {"error": "Miktar geçerli bir sayı olmalıdır."}

    from_code = str(from_code).upper().strip()
    to_code = str(to_code).upper().strip()

    if from_code == to_code:
        return {
            "amount": amount,
            "from": from_code,
            "to": to_code,
            "result": amount,
        }

    url = f"https://api.frankfurter.app/latest?amount={amount}&from={from_code}&to={to_code}"
    try:
        res = requests.get(url, timeout=5).json()
        if "rates" in res and to_code in res["rates"]:
            return {
                "amount": amount,
                "from": from_code,
                "to": to_code,
                "result": float(res["rates"][to_code]),
            }
        return {
            "error": f"Döviz dönüşümü gerçekleştirilemedi ({from_code} -> {to_code})."
        }
    except Exception as e:
        return {"error": f"API Hatası: {str(e)}"}


def calculate_crypto_purchase(amount_fiat, price_per_coin) -> dict:
    try:
        amount_fiat = float(amount_fiat)
        price_per_coin = float(price_per_coin)
    except Exception:
        return {"error": "Parametreler geçerli bir sayı olmalıdır."}

    if price_per_coin <= 0:
        return {"error": "Coin fiyatı 0'dan büyük olmalıdır."}

    return {
        "amount_fiat": amount_fiat,
        "price_per_coin": price_per_coin,
        "crypto_purchased": round(amount_fiat / price_per_coin, 8),
    }


