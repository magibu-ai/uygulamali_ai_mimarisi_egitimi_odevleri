def kitap_bilgisi_topla(kitap_adi):
    headers = {
        "User-Agent": "TurkKlasikKitaplariDatasetOdevi/1.0"
    }

    try:
        # Önce kitabın Wikipedia sayfasını arıyoruz.
        arama_url = "https://tr.wikipedia.org/w/api.php"

        arama_parametreleri = {
            "action": "query",
            "list": "search",
            "srsearch": f'"{kitap_adi}" roman',
            "format": "json",
            "utf8": 1
        }

        arama_cevabi = requests.get(
            arama_url,
            params=arama_parametreleri,
            headers=headers,
            timeout=20
        )

        if arama_cevabi.status_code != 200:
            return {
                "kitap": kitap_adi,
                "sayfa_basligi": "",
                "bilgi": "",
                "kaynak": "",
                "durum": f"Arama hatası: {arama_cevabi.status_code}"
            }

        arama_sonuclari = arama_cevabi.json()["query"]["search"]

        if not arama_sonuclari:
            return {
                "kitap": kitap_adi,
                "sayfa_basligi": "",
                "bilgi": "",
                "kaynak": "",
                "durum": "Sayfa bulunamadı"
            }

        # Arama sonucundaki ilk sayfanın başlığını alıyoruz.
        sayfa_basligi = arama_sonuclari[0]["title"]

        sayfa_url = (
            "https://tr.wikipedia.org/wiki/"
            + quote(sayfa_basligi.replace(" ", "_"))
        )

        # Bulduğumuz sayfanın HTML içeriğini indiriyoruz.
        sayfa_cevabi = requests.get(
            sayfa_url,
            headers=headers,
            timeout=20
        )

        if sayfa_cevabi.status_code != 200:
            return {
                "kitap": kitap_adi,
                "sayfa_basligi": sayfa_basligi,
                "bilgi": "",
                "kaynak": sayfa_url,
                "durum": f"Sayfa hatası: {sayfa_cevabi.status_code}"
            }

        # HTML içinden paragrafları çekiyoruz.
        soup = BeautifulSoup(sayfa_cevabi.text, "html.parser")
        paragraflar = soup.find_all("p")

        uygun_paragraflar = []

        for paragraf in paragraflar:
            metin = paragraf.get_text(" ", strip=True)

            if len(metin) >= 100:
                uygun_paragraflar.append(metin)

            # Her kitap için ilk üç uygun paragrafı alıyoruz.
            if len(uygun_paragraflar) == 3:
                break

        bilgi = " ".join(uygun_paragraflar)

        return {
            "kitap": kitap_adi,
            "sayfa_basligi": sayfa_basligi,
            "bilgi": bilgi,
            "kaynak": sayfa_url,
            "durum": "Başarılı" if bilgi else "Metin bulunamadı"
        }

    except Exception as hata:
        return {
            "kitap": kitap_adi,
            "sayfa_basligi": "",
            "bilgi": "",
            "kaynak": "",
            "durum": f"Hata: {hata}"
        }

