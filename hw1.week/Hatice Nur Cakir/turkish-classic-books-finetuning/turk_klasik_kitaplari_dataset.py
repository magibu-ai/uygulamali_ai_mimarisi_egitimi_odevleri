def metinden_soru_cevap_ayir(metin, kitap):
    bulunanlar = []
    mevcut_soru = None

    for satir in metin.splitlines():
        # Markdown işaretlerini temizle
        temiz = re.sub(r"[*#`]", "", satir).strip()

        if not temiz or ":" not in temiz:
            continue

        baslik, icerik = temiz.split(":", 1)
        baslik_kucuk = baslik.lower().strip()
        icerik = icerik.strip()

        # "Soru", "Sorusu", "Sorusunda" gibi biçimleri yakala
        if "soru" in baslik_kucuk and icerik:
            mevcut_soru = icerik

        # "Cevap", "Cevabı" gibi biçimleri yakala
        elif "cev" in baslik_kucuk and icerik and mevcut_soru:
            if not mevcut_soru.endswith("?"):
                mevcut_soru += "?"

            bulunanlar.append({
                "kitap": kitap,
                "soru": mevcut_soru,
                "cevap": icerik
            })

            mevcut_soru = None

    return bulunanlar

