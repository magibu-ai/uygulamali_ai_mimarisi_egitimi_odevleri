FastLanguageModel.for_inference(model)

mesajlar = [
    {
        "role": "user",
        "content": "Araba Sevdası romanının yazarı kimdir?"
    }
]

girdi = tokenizer.apply_chat_template(
    mesajlar,
    tokenize=True,
    add_generation_prompt=True,
    return_tensors="pt"
).to("cuda")

cikti = model.generate(
    input_ids=girdi,
    max_new_tokens=80,
    do_sample=False,
    use_cache=True
)

yeni_tokenlar = cikti[0][girdi.shape[1]:]

cevap = tokenizer.decode(
    yeni_tokenlar,
    skip_special_tokens=True
)

print("Modelin cevabı:")
print(cevap)

