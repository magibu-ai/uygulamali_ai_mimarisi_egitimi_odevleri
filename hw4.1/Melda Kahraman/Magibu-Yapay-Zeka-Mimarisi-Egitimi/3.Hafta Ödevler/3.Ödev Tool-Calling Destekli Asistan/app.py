def create_order(comic_id: int, quantity: int, customer_name: str):
    conn = sqlite3.connect('comic_store.db')
    cursor = conn.cursor()

    cursor.execute('SELECT title, price, stock FROM comics WHERE id = ?', (comic_id,))
    comic = cursor.fetchone()

    if not comic:
        conn.close()
        return json.dumps({"error": "Geçersiz Çizgi Roman ID!"}, ensure_ascii=False)

    title, price, stock = comic

    if stock < quantity:
        conn.close()
        return json.dumps({"error": f"Yetersiz stok! Mevcut stok: {stock}, İstenen: {quantity}"}, ensure_ascii=False)

    total_price = price * quantity
    cursor.execute('''
        INSERT INTO orders (customer_name, comic_id, quantity, total_price)
        VALUES (?, ?, ?, ?)
    ''', (customer_name, comic_id, quantity, total_price))

    new_stock = stock - quantity
    cursor.execute('UPDATE comics SET stock = ? WHERE id = ?', (new_stock, comic_id))

    order_id = cursor.lastrowid
    conn.commit()
    conn.close()

    return json.dumps({
        "status": "Başarılı",
        "order_id": order_id,
        "customer_name": customer_name,
        "comic_title": title,
        "quantity": quantity,
        "total_price": f"{total_price} TL",
        "remaining_stock": new_stock
    }, ensure_ascii=False)

