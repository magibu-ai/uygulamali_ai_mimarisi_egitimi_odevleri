def get_comics_catalog():
    conn = sqlite3.connect('comic_store.db')
    cursor = conn.cursor()
    cursor.execute('SELECT id, title, publisher, price, stock FROM comics')
    rows = cursor.fetchall()
    conn.close()

    catalog = []
    for r in rows:
        catalog.append({
            "id": r[0],
            "title": r[1],
            "publisher": r[2],
            "price": f"{r[3]} TL",
            "stock": r[4]
        })
    return json.dumps(catalog, ensure_ascii=False)

